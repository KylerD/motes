import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const url = process.env.MOTES_URL || 'http://127.0.0.1:5175';
mkdirSync('captures-cozy', { recursive: true });
const browser = await chromium.launch();
const failures = [];
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  const page = await desktop.newPage();
  await page.addInitScript(() => {
    const create = AudioContext.prototype.createDynamicsCompressor;
    AudioContext.prototype.createDynamicsCompressor = function () {
      const node = create.call(this), analyser = this.createAnalyser();
      node.connect(analyser); window.__audioProbe = analyser; return node;
    };
  });
  page.on('pageerror', e => failures.push(e.message));
  await page.goto(`${url}/?debug&seed=2718`);
  await page.waitForFunction(() => window.__tidepool);
  await page.screenshot({ path: 'captures-cozy/desktop.png' });
  assert.equal(await page.evaluate(() => window.__tidepool.paused), true);
  await page.getByRole('button', { name: 'Play simulation', exact: true }).click();
  await page.waitForFunction(() => window.__tidepool.pool.step > 30);
  await page.getByRole('button', { name: 'Pause simulation', exact: true }).click();
  const stopped = await page.evaluate(() => window.__tidepool.pool.step);
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => window.__tidepool.pool.step), stopped);
  await page.locator('#specimen-select').selectOption({ index: 1 });
  assert.equal(await page.locator('#specimen').isVisible(), true);
  await page.locator('#follow').click();
  assert.equal(await page.locator('#follow').getAttribute('aria-pressed'), 'true');
  await page.locator('#fit').click();
  await page.getByRole('button', { name: 'Explore', exact: true }).click();
  await page.locator('#lens').selectOption('energy');
  await page.screenshot({ path: 'captures-cozy/desktop-inspect.png' });
  await page.locator('#deselect').click();
  await page.locator('#lens').selectOption('life');
  const body = await page.evaluate(() => window.__tidepool.pool.cells[7]);
  const point = await page.evaluate(({ x, y }) => window.__tidepool.project(x, y), body);
  await page.locator('[data-tool="feed"]').click();
  const nutrients = await page.evaluate(() => window.__tidepool.pool.nutrients.length);
  await page.locator('#pool').click({ position: point });
  assert.equal(await page.evaluate(() => window.__tidepool.pool.nutrients.length), nutrients + 1);
  await page.locator('#branch').click();
  assert.equal(await page.locator('#comparison').isVisible(), true);
  await page.locator('[data-tool="cut"]').click();
  const bonds = await page.evaluate(() => window.__tidepool.pool.bonds.length);
  await page.locator('#pool').click({ position: point });
  assert.ok(await page.evaluate(() => window.__tidepool.pool.bonds.length) < bonds);
  assert.ok(await page.evaluate(() => window.__tidepool.reference.bonds.length > window.__tidepool.pool.bonds.length));
  await page.locator('#show-original').click();
  assert.equal(await page.locator('#show-original').getAttribute('aria-pressed'), 'true');
  await page.locator('#show-branch').click();
  await page.locator('[data-tool="current"]').click();
  await page.locator('#pool').click({ position: point });
  assert.ok(await page.evaluate(() => window.__tidepool.pool.disturbances.length) > 0);
  await page.evaluate(() => window.__tidepool.advance(300));
  await page.locator('#timeline').fill('30');
  assert.equal(await page.evaluate(() => window.__tidepool.pool.step), 30);
  assert.equal(await page.evaluate(() => window.__tidepool.reference.step), 30);
  const saved = await page.evaluate(() => window.__tidepool.export());
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#save').click();
  const download = await downloadEvent;
  assert.match(download.suggestedFilename(), /^motes-2718-/);
  await page.locator('#file').setInputFiles({ name: 'saved.json', mimeType: 'application/json', buffer: Buffer.from(saved) });
  await page.waitForFunction(() => document.querySelector('#observation').textContent.includes('Welcome back'));
  assert.equal(await page.evaluate(() => window.__tidepool.pool.step), 30);
  await page.locator('#file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":"bad"}') });
  await page.waitForFunction(() => document.querySelector('#observation').textContent.includes('not a valid'));
  assert.equal(await page.evaluate(() => window.__tidepool.pool.step), 30);
  await page.locator('#sound').click();
  await page.waitForFunction(() => document.querySelector('#sound').getAttribute('aria-pressed') === 'true');
  await page.locator('#volume').fill('30');
  await page.locator('#play').click();
  const sound = await page.evaluate(async () => {
    let peak = 0, squares = 0, count = 0;
    for (let i = 0; i < 30; i++) {
      await new Promise(resolve => setTimeout(resolve, 100));
      const values = new Float32Array(window.__audioProbe.fftSize);
      window.__audioProbe.getFloatTimeDomainData(values);
      for (const v of values) { peak = Math.max(peak, Math.abs(v)); squares += v * v; count++; }
    }
    return { peak, rms: Math.sqrt(squares / count) };
  });
  assert.ok(sound.rms > 0.0001 && sound.peak < 0.95, JSON.stringify(sound));
  await page.locator('#play').click();
  await page.locator('#sound').click();
  assert.equal(await page.locator('#sound').getAttribute('aria-pressed'), 'false');
  await page.locator('#guide-open').click();
  assert.equal(await page.locator('#guide').isVisible(), true);
  await page.keyboard.press('Escape');
  await page.locator('#habitat').selectOption('spores');
  assert.equal(await page.evaluate(() => window.__tidepool.pool.bonds.length), 0);
  await page.locator('#seed-button').click();
  await page.locator('#seed-input').fill('42');
  await page.getByRole('button', { name: 'Open world', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__tidepool.pool.seed), 42);
  await page.locator('#habitat').selectOption('reef');
  await page.locator('#new-world').click();
  assert.notEqual(await page.evaluate(() => window.__tidepool.pool.seed), 42);
  const diagnostics = await page.evaluate(() => window.__tidepool.rendering);
  await page.goto(`${url}/original.html?cycle=1000`);
  await page.locator('#world').waitFor();
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, reducedMotion: 'reduce' });
  const phone = await mobile.newPage(); phone.on('pageerror', e => failures.push(e.message));
  await phone.goto(`${url}/?debug&seed=2718`); await phone.waitForFunction(() => window.__tidepool);
  await phone.screenshot({ path: 'captures-cozy/mobile.png' });
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await phone.locator('#explore').tap();
  await phone.screenshot({ path: 'captures-cozy/mobile-explore.png' });
  await phone.locator('#specimen-select').selectOption({ index: 1 });
  assert.equal(await phone.locator('#specimen').isVisible(), true);
  await phone.locator('#guide-open').tap();
  assert.equal(await phone.locator('#guide').isVisible(), true);
  await phone.locator('#guide-close').tap();
  assert.deepEqual(failures, []);
  writeFileSync('captures-cozy/verification.json', JSON.stringify({ passed: true, errors: failures, rendering: diagnostics, desktop: '1440x960', mobile: '390x844', checks: ['transport', 'selection', 'follow', 'lenses', 'feed', 'sever', 'current', 'fork/compare', 'rewind', 'save/open', 'invalid-file', 'audio/volume', 'seed/presets', 'guide', 'original-route', 'mobile'] }, null, 2));
  console.log(JSON.stringify({ passed: true, rendering: diagnostics, sound, browserErrors: failures }));
} finally { await browser.close(); }
